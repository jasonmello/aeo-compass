#!/usr/bin/env node
// Generates the global JSON-LD (entity + WebSite [+ app]) from aeo/profile.json.
// Usage: node generate-schema.mjs [--profile aeo/profile.json] [--html] [--out file [--force]]
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from './lib.mjs';

const args = parseArgs();
const profilePath = path.resolve(args.profile || 'aeo/profile.json');
if (!fs.existsSync(profilePath)) { console.error(`Could not find ${profilePath}. Copy <skill>/templates/profile.json to aeo/profile.json and fill it in (SKILL.md, step 0).`); process.exit(1); }
let p;
try { p = JSON.parse(fs.readFileSync(profilePath, 'utf8')); } catch (err) { console.error(`${profilePath} is invalid: ${err.message}`); process.exit(1); }

const clean = (o) => {
  if (Array.isArray(o)) { const a = o.map(clean).filter((v) => v !== undefined); return a.length ? a : undefined; }
  if (o && typeof o === 'object') {
    const r = {};
    for (const [k, v] of Object.entries(o)) { const c = clean(v); if (c !== undefined) r[k] = c; }
    return Object.keys(r).length ? r : undefined;
  }
  return o === '' || o === null || o === undefined ? undefined : o;
};

const missing = [];
for (const k of ['name', 'url', 'description']) if (!p[k]) missing.push(k);
if (missing.length) { console.error(`Required fields empty in profile.json: ${missing.join(', ')}`); process.exit(1); }
try { if (!new URL(p.url).hostname) throw 0; } catch { console.error("Field 'url' is invalid in profile.json: use the full domain, e.g. https://example.com"); process.exit(1); }
if (p.description.trim().length < 20) { console.error("Field 'description' is too short: write a full sentence (what it does, for whom and where)."); process.exit(1); }

const url = p.url.replace(/\/$/, '');
const orgId = `${url}/#organization`;
const type = p.type || 'Organization';
const isPerson = type === 'Person';
const sameAs = Object.values(p.profiles || {}).filter(Boolean);
const a = p.address || {};
const hasAddress = a.street && a.city;

const entity = {
  '@type': type,
  '@id': orgId,
  name: p.name,
  url,
  description: p.description,
  ...(isPerson ? { image: p.logo, jobTitle: p.jobTitle } : { logo: p.logo, foundingDate: p.foundingDate, legalName: p.legalName, taxID: p.taxID }),
  telephone: p.telephone,
  email: p.email,
  sameAs,
  address: hasAddress ? { '@type': 'PostalAddress', streetAddress: a.street, addressLocality: a.city, addressRegion: a.state, postalCode: a.postalCode, addressCountry: a.country } : undefined,
  geo: p.geo?.lat != null && p.geo?.lng != null ? { '@type': 'GeoCoordinates', latitude: p.geo.lat, longitude: p.geo.lng } : undefined,
  hasMap: p.mapUrl,
  areaServed: p.areaServed,
  priceRange: p.priceRange,
  openingHoursSpecification: (p.openingHours || []).filter((h) => h.opens && h.closes).map((h) => ({ '@type': 'OpeningHoursSpecification', dayOfWeek: h.days, opens: h.opens, closes: h.closes })),
  founder: !isPerson && p.founder?.name ? { '@type': 'Person', name: p.founder.name, jobTitle: p.founder.jobTitle, url: p.founder.url, sameAs: p.founder.profiles } : undefined,
};

const graph = [
  entity,
  { '@type': 'WebSite', '@id': `${url}/#website`, url, name: p.name, inLanguage: p.language || 'en', publisher: { '@id': orgId } },
];

if (p.app?.name) {
  graph.push({
    '@type': p.app.type || 'SoftwareApplication',
    name: p.app.name,
    applicationCategory: p.app.category,
    operatingSystem: p.app.operatingSystem,
    url: p.app.url,
    downloadUrl: p.app.storeUrl,
    offers: p.app.price !== '' && p.app.price != null ? { '@type': 'Offer', price: String(p.app.price), priceCurrency: p.app.currency || 'USD' } : undefined,
    publisher: { '@id': orgId },
  });
}

const json = clean({ '@context': 'https://schema.org', '@graph': graph });
const out = args.html
  ? `<script type="application/ld+json">\n${JSON.stringify(json, null, 2)}\n</script>\n`
  : JSON.stringify(json, null, 2) + '\n';

if (args.out) {
  // Without --force, only overwrite when the target is already output of this script (plain JSON-LD).
  const current = fs.existsSync(args.out) ? fs.readFileSync(args.out, 'utf8').trimStart() : null;
  if (current !== null && !args.force && !/^(<script type="application\/ld\+json">|\{\s*"@context")/.test(current)) { console.error(`${args.out} already exists and is not JSON-LD generated by this script. Pick another target or use --force to overwrite.`); process.exit(1); }
  fs.mkdirSync(path.dirname(path.resolve(args.out)), { recursive: true }); fs.writeFileSync(args.out, out); console.error(`Written to ${args.out}`); }
else process.stdout.write(out);

const warnings = [];
if (sameAs.length < 2) warnings.push('fewer than 2 profiles in "profiles" (weak sameAs)');
if (/Business|Dentist|Clinic|Store|Restaurant|Service/.test(type) && !hasAddress) warnings.push('local type without an address');
if (!p.logo) warnings.push('no logo');
if (warnings.length) console.error(`Warnings: ${warnings.join('; ')}`);
